#!/usr/bin/env python3
"""Embeds files as C++ byte arrays (the TypeScript runtime).

Replaces cmake/EmbedFiles.cmake. Writes a namespace Mercury table:
    const EmbeddedFile kTsRuntimeFiles[] = {{path, data, size}, ...};
    const size_t kTsRuntimeFileCount = N;
"""

from __future__ import annotations

import argparse
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    parser.add_argument("--root", required=True)
    parser.add_argument("files", nargs="+")
    args = parser.parse_args()

    root = Path(args.root)
    files = sorted(Path(f) for f in args.files)

    content = [
        "// Generated by tools/embed_files.py. Do not edit.",
        '#include "scripting/ts_types.h"',
        "",
        "namespace Mercury {",
        "",
    ]
    table = []
    for index, path in enumerate(files):
        relative = path.relative_to(root).as_posix()
        data = path.read_bytes()
        bytes_text = "".join(f"0x{byte:02x}," for byte in data) or "0x00,"
        content.append(
            f"static const unsigned char kFile{index}[] = " + bytes_text + "0};"
        )
        table.append(f'    {{"{relative}", kFile{index}, {len(data)}}},')
        content.append("")

    content.append("const EmbeddedFile kTsRuntimeFiles[] = {")
    content.extend(table)
    content.append("};")
    content.append(f"const size_t kTsRuntimeFileCount = {len(files)};")
    content.append("}  // namespace Mercury")
    content.append("")

    out = Path(args.out)
    out.write_text("\n".join(content))


if __name__ == "__main__":
    main()
