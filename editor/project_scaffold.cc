std::string Slug(std::string text) {
  std::string slug;
  for (unsigned char c : text) {
    if (std::isalnum(c)) {
      slug.push_back(static_cast<char>(std::tolower(c)));
    } else if (!slug.empty() && slug.back() != '_') {
      slug.push_back('_');
    }
  }
  while (!slug.empty() && slug.back() == '_') slug.pop_back();
  return slug.empty() ? "game" : slug;
}

std::string GameTarget(const Project& project) {
  const std::string target = project.GetBuildTarget();
  return target.empty() ? Slug(project.GetName()) : target;
}

std::string SystemsTarget(const Project& project) {
  const std::string target = project.GetBuildSystemsTarget();
  return target.empty() ? GameTarget(project) + "_systems" : target;
}

bool WriteIfMissing(const fs::path& file, const std::string& text) {
  std::error_code ec;
  // symlink_status: a dangling link planted in a cloned project counts as
  // "something is there" and is never written through.
  if (fs::symlink_status(file, ec).type() != fs::file_type::not_found) {
    return true;
  }
  fs::create_directories(file.parent_path(), ec);
  return os::WriteFileAtomic(file, text);
}

std::string CMakeListsText(const Project& project) {
  const std::string target = GameTarget(project);
  const std::string systems = SystemsTarget(project);
  return std::format(
      R"(# Generated by the Mercury Editor. This file belongs to you after it is
# created; the editor only regenerates it when it is missing.
#
# Build with the presets:
#   cmake --preset debug
#   cmake --build --preset debug
#
# A packaged Mercury editor sets Mercury_DIR for you. For a command line build,
# point MERCURY_SDK at the editor's Contents/Resources/sdk (or SDK prefix).
cmake_minimum_required(VERSION 3.25)
project({0} CXX)

find_package(Mercury CONFIG REQUIRED)

# Game code in src/ is linked into the game executable.
mercury_add_game({1} PROJECT "${{CMAKE_CURRENT_SOURCE_DIR}}")

# Editor extensions in system/ are built as a module the editor loads. A
# release/packaging configure can turn them off to skip the wxWidgets check.
option(MERCURY_BUILD_EDITOR_SYSTEMS "Build the project's editor extensions" ON)
if (MERCURY_BUILD_EDITOR_SYSTEMS)
    mercury_add_editor_system({2} PROJECT "${{CMAKE_CURRENT_SOURCE_DIR}}")
endif ()

# Link your own libraries here, e.g. the multiplayer path:
# target_link_libraries({1} PRIVATE enet)
)",
      Slug(project.GetName()), target, systems);
}

