std::string ClangdText() {
  const os::EngineSdkPaths sdk = os::EngineSdkDir();
  // A YAML single-quoted scalar is safe for spaces and backslashes; a single
  // quote is doubled. The value must be exactly "-I/path" (no quotes inside
  // the argument), or the compiler sees them as part of the folder name.
  auto flag = [](const std::string& value) {
    std::string out = "    - '";
    for (char c : value) {
      if (c == '\'')
        out += "''";
      else
        out.push_back(c);
    }
    out += "'\n";
    return out;
  };

  std::string out =
      "# Generated by the Mercury Editor. Do not edit; it is rewritten every\n"
      "# time the project opens and tracks the editor it is running in.\n"
      "CompileFlags:\n"
      "  CompilationDatabase: .mercury/build/debug\n"
      "  Add:\n"
      "    - '-std=c++20'\n";

  std::vector<fs::path> include_dirs = sdk.include_dirs;
  // The Vulkan headers are found by CMake through find_package(Vulkan), not
  // through the SDK's include folder. Add the usual locations so a header
  // glfw3.h pulls in for editor-system code resolves outside the compilation
  // database too.
  std::vector<fs::path> vulkan_candidates;
  if (const char* vulkan_sdk = std::getenv("VULKAN_SDK")) {
    vulkan_candidates.push_back(fs::path(vulkan_sdk) / "include");
  }
  vulkan_candidates.push_back("/opt/homebrew/include");
  vulkan_candidates.push_back("/usr/local/include");
  for (const fs::path& candidate : vulkan_candidates) {
    std::error_code ec;
    if (!fs::is_regular_file(candidate / "vulkan" / "vulkan.h", ec)) continue;
    if (std::find(include_dirs.begin(), include_dirs.end(), candidate) ==
        include_dirs.end()) {
      include_dirs.push_back(candidate);
    }
  }

  for (const fs::path& dir : include_dirs) {
    out += flag("-I" + dir.string());
  }
  out += flag("-Isrc");
  out += flag("-Isystem");
  out += flag("-DMERCURY_GRAPHICS_VULKAN=1");
  out += flag("-DGLFW_INCLUDE_VULKAN=1");
  out += flag("-DGLM_FORCE_DEPTH_ZERO_TO_ONE=1");
  return out;
}

