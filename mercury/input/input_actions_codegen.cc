#include "input_actions_codegen.h"

#include <cctype>
#include <map>
#include <set>

namespace Mercury {

std::string InputActionIdentifier(std::string_view name) {
  std::string out;
  bool upper = true;
  for (unsigned char c : name) {
    if (!std::isalnum(c) && c != '_') {
      upper = true;
      continue;
    }
    out += upper ? static_cast<char>(std::toupper(c)) : static_cast<char>(c);
    upper = false;
  }
  if (out.empty()) return "Default";
  if (std::isdigit(static_cast<unsigned char>(out[0]))) out.insert(out.begin(), '_');
  return out;
}

namespace {

std::string Quote(std::string_view text) {
  std::string out = "\"";
  for (char c : text) {
    if (c == '"' || c == '\\') out += '\\';
    out += c;
  }
  return out + "\"";
}

}  // namespace

InputActionsHeader GenerateInputActionsHeader(const InputActionsDesc& desc,
                                              std::string_view class_name,
                                              std::string_view source_path) {
  InputActionsHeader header;
  const std::string type = InputActionIdentifier(class_name);

  // Map identifier -> its actions, in map order.
  std::vector<std::pair<std::string, std::vector<const InputActionDesc*>>> maps;
  std::map<std::string, std::string> map_names;  // identifier -> first map name
  for (const auto& map : desc.maps) {
    const std::string id = InputActionIdentifier(map);
    if (auto [it, added] = map_names.emplace(id, map); !added) {
      header.errors.push_back("maps \"" + it->second + "\" and \"" + map + "\" are both " + id);
      continue;
    }
    maps.push_back({id, {}});
  }
  for (const auto& action : desc.actions) {
    const std::string id = InputActionIdentifier(action.map);
    for (auto& [map_id, actions] : maps) {
      if (map_id == id && map_names[id] == action.map) actions.push_back(&action);
    }
  }

  std::string& s = header.source;
  s += "// Generated by Mercury from " + std::string(source_path) + ". Do not edit.\n";
  s += "#pragma once\n\n";
  s += "#include <string_view>\n\n";
  s += "#include \"input/input_actions.h\"\n\n";
  s += "struct " + type + " {\n";
  for (const auto& [map_id, actions] : maps) {
    std::set<std::string> action_ids;
    s += "  struct " + map_id + "Actions {\n";
    for (const auto* action : actions) {
      const std::string id = InputActionIdentifier(action->name);
      if (!action_ids.insert(id).second) {
        header.errors.push_back("two actions in \"" + action->map + "\" are both " + id);
        continue;
      }
      s += "    Mercury::InputAction* " + id + ";\n";
    }
    s += "\n    void Enable(Mercury::InputActionAsset& asset) const { asset.EnableMap(" +
         Quote(map_names[map_id]) + "); }\n";
    s += "    void Disable(Mercury::InputActionAsset& asset) const { asset.DisableMap(" +
         Quote(map_names[map_id]) + "); }\n";
    s += "  } " + map_id + ";\n\n";
  }

  // Full names, for GetInputActions()->Find(GameInput::kPlayerJump).
  for (const auto& [map_id, actions] : maps) {
    for (const auto* action : actions) {
      s += "  static constexpr std::string_view k" + map_id +
           InputActionIdentifier(action->name) + " = " + Quote(action->FullName()) + ";\n";
    }
  }
  if (!desc.actions.empty()) s += "\n";

  s += "  explicit " + type + "(Mercury::InputActionAsset& asset)";
  bool first = true;
  for (const auto& [map_id, actions] : maps) {
    s += first ? "\n      : " : ",\n        ";
    first = false;
    s += map_id + "{";
    std::set<std::string> action_ids;
    bool first_action = true;
    for (const auto* action : actions) {
      if (!action_ids.insert(InputActionIdentifier(action->name)).second) continue;
      if (!first_action) s += ", ";
      first_action = false;
      s += "asset.Find(" + Quote(action->FullName()) + ")";
    }
    s += "}";
  }
  s += " {}\n";
  s += "};\n";
  return header;
}

}  // namespace Mercury
