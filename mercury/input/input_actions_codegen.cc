#include "input_actions_codegen.h"

#include <cctype>
#include <map>
#include <set>

namespace Mercury {

std::string InputActionIdentifier(std::string_view name) {
  std::string out;
  bool upper = true;
  for (unsigned char c : name) {
    if (!std::isalnum(c) && c != '_') {
      upper = true;
      continue;
    }
    out += upper ? static_cast<char>(std::toupper(c)) : static_cast<char>(c);
    upper = false;
  }
  if (out.empty()) return "Default";
  if (std::isdigit(static_cast<unsigned char>(out[0])))
    out.insert(out.begin(), '_');
  return out;
}

namespace {

std::string Quote(std::string_view text) {
  std::string out = "\"";
  for (char c : text) {
    if (c == '"' || c == '\\') out += '\\';
    out += c;
  }
  return out + "\"";
}

}  // namespace

InputActionsSource GenerateInputActionsAngelScript(
    const InputActionsDesc& desc, std::string_view class_name,
    std::string_view source_path) {
  InputActionsSource result;
  const std::string type = InputActionIdentifier(class_name);

  // Map identifier -> its actions, in map order.
  std::vector<std::pair<std::string, std::vector<const InputActionDesc*>>> maps;
  std::map<std::string, std::string> map_names;  // identifier -> first map name
  for (const auto& map : desc.maps) {
    const std::string id = InputActionIdentifier(map);
    if (auto [it, added] = map_names.emplace(id, map); !added) {
      result.errors.push_back("maps \"" + it->second + "\" and \"" + map +
                              "\" are both " + id);
      continue;
    }
    maps.push_back({id, {}});
  }
  for (const auto& action : desc.actions) {
    const std::string id = InputActionIdentifier(action.map);
    for (auto& [map_id, actions] : maps) {
      if (map_id == id && map_names[id] == action.map)
        actions.push_back(&action);
    }
  }

  std::string& s = result.source;
  s += "// Generated by Mercury from " + std::string(source_path) +
       ". Do not edit.\n";
  s += "// Usage: InputAction action = Input::RequireAction(" + type +
       "::Map::Action);\n\n";
  s += "namespace " + type + "\n{\n";
  for (const auto& [map_id, actions] : maps) {
    std::set<std::string> action_ids;
    s += "    namespace " + map_id + "\n    {\n";
    s += "        const string Map = " + Quote(map_names[map_id]) + ";\n";
    for (const auto* action : actions) {
      const std::string id = InputActionIdentifier(action->name);
      if (!action_ids.insert(id).second) {
        result.errors.push_back("two actions in \"" + action->map +
                                "\" are both " + id);
        continue;
      }
      s += "        const string " + id + " = " + Quote(action->FullName()) +
           ";\n";
    }
    s += "    }\n";
  }
  s += "\n";
  for (const auto& [map_id, actions] : maps) {
    s += "    void Enable" + map_id + "() { Input::EnableMap(" + map_id +
         "::Map, true); }\n";
    s += "    void Disable" + map_id + "() { Input::EnableMap(" + map_id +
         "::Map, false); }\n";
  }
  s += "}\n";
  return result;
}

}  // namespace Mercury
