/**
 * @brief What a scene may ask of the application that renders it
 *
 * The editor uses this to draw the scene into a texture shown inside an
 * ImGui panel instead of straight to the window.
 */
class RenderHost {
 public:
  virtual ~RenderHost() = default;

  // Render the scene into an offscreen texture instead of the window.
  virtual void EnableSceneTexture(bool enabled) {}
  // Size of the offscreen texture; takes effect from the next frame.
  virtual void SetSceneViewportSize(int width, int height) {}
  // ImTextureID of the offscreen texture, or 0 before it exists.
  virtual uint64_t GetSceneTexture() const { return 0; }
  // Also render this frame from `camera` (an entity with a Camera and a
  // Transform) into a separate width x height texture; entt::null skips it.
  // Call every frame the preview is shown.
  virtual void SetPreviewCamera(kEntityId camera, int width, int height) {}
  // ImTextureID of the preview texture, or 0 before it exists.
  virtual uint64_t GetPreviewTexture() const { return 0; }
  // Also render a UI draw list into a separate width x height texture over
  // `background` (the editor's UI Builder canvas). Call every frame it is
  // shown; the draw data must stay alive until the frame is rendered.
  virtual void SetUIPreview(const UI::UIDrawData* draw_data, int width, int height,
                            glm::vec4 background) {}
  // ImTextureID of the UI preview texture, or 0 before it exists.
  virtual uint64_t GetUIPreviewTexture() const { return 0; }
  // The FPS overlay drawn in the top-left corner.
  virtual void SetShowRenderStats(bool show) {}
  virtual int GetAverageFps() const { return 0; }
  virtual void SetWindowTitle(const std::string& title) {}
};

/**
 * @brief One directional light plus ambient light, used by lit meshes
 */
struct SceneLighting {
  glm::vec3 direction = glm::normalize(glm::vec3(-0.4f, -1.0f, -0.6f));
  glm::vec3 color = glm::vec3(1.0f);  // color * intensity
  glm::vec3 ambient = glm::vec3(0.2f);         // from above
  glm::vec3 ambient_ground = glm::vec3(0.07f);  // from below
  bool cast_shadows = true;
  float shadow_bias = 0.0015f;
  float shadow_normal_bias = 0.035f;
  float shadow_distance = 120.0f;
};

/**
 * @brief Post-processing and renderer features for the frame (a URP volume
 * profile plus the renderer's features)
 */
struct RenderSettings {
  // Off: the scene renders as before post-processing existed (tonemapped in
  // the lit shader).
  bool post_processing = false;
  int tonemap = 1;  // 0 none, 1 neutral, 2 ACES
  float exposure = 1.0f;
  float bloom_intensity = 0.0f;
  float bloom_threshold = 1.0f;
  float bloom_scatter = 0.7f;
  float vignette_intensity = 0.0f;
  float vignette_smoothness = 0.2f;
  glm::vec2 vignette_center = glm::vec2(0.5f);
  float ssao_intensity = 0.0f;
  float ssao_radius = 0.3f;
  int ssao_samples = 12;
  bool fxaa = false;
  // Linework's wide outline around objects on these rendering layers.
  uint32_t outline_layers = 0;
  glm::vec4 outline_color = glm::vec4(1.0f);
  float outline_width = 3.0f;
};

/**
 * @brief A camera the renderer draws this frame, in drawing order
 */
struct RenderCamera {
  kEntityId entity = entt::null;
  glm::mat4 view = glm::mat4(1.0f);
  glm::mat4 projection = glm::mat4(1.0f);
  glm::vec3 position = glm::vec3(0.0f);
  float near_clip = 0.1f;
  float far_clip = 1000.0f;
  uint32_t culling_mask = 0xffffffffu;
  int clear = 0;  // CameraClear: 0 skybox, 1 color, 2 depth only, 3 nothing
  glm::vec4 background = glm::vec4(0.1f, 0.1f, 0.1f, 1.0f);
  bool overlay = false;
  std::string target_texture;  // res:// RenderTexture; "" = the screen
  int target_width = 0;
  int target_height = 0;
  bool post_processing = true;
};

/**
 * @brief Universal abstraction around how worlds are created and modified
 *
 * Game scenes contain everything a renderer can need to draw to the screen.
 * There is no platform specific code and instead what it does is generate
 * different types of primitives that are specific. For example, for simple
 * shapes like cubes the primitives are only triangle vertices with color and it
 * can be generated by the application. Then the application can render it
 * however it likes(one by one or batched) and create the shaders required for
 * each primitive type
 *
 */
class GameScene {
 public:
  virtual ~GameScene() = default;
  GameScene();

  virtual void OnStart() = 0;
  // Fixed ticks per second the application runs OnTick (and physics) at.
  virtual int GetTicksPerSecond() const { return 60; }
  virtual void OnFrame(double delta_t) = 0;  // delta time in ms
  virtual void OnTick(double delta_t) = 0;   // delta time in ms
  virtual void OnDestroy() = 0;

  /**
   * @brief Called when the user tries to close the window
   * @return false to keep the window open (e.g. to ask about unsaved work);
   * call QuitScene() later to close it
   */
  virtual bool OnCloseRequested() { return true; }

  bool GetCameraProj(glm::mat4x4&);
  bool GetCameraPosition(glm::vec3&);
  // Inverse of the camera's projection * rotation-only view: maps an NDC
  // point to a world-space view direction, for drawing the skybox.
  bool GetSkyboxMatrix(glm::mat4x4&);
  // Matrices for rendering from any camera entity at the given size: its
  // projection * view, the skybox matrix (as above), and its position.
  bool GetCameraMatrices(kEntityId camera, float width, float height,
                         glm::mat4x4& view_proj, glm::mat4x4& skybox,
                         glm::vec3& position);

  SceneLighting& GetLighting() { return lighting_; }
  // The entity the game is rendered from (it has a Camera and a Transform).
  kEntityId GetPlayerCamera() const { return player_camera_; }
  glm::vec4 GetClearColor() const { return clear_color_; }
  void SetClearColor(glm::vec4 color) { clear_color_ = color; }
  // Absolute path of the skybox panorama, or "" to use the clear color.
  const std::string& GetSkyboxPath() const { return skybox_path_; }
  void SetSkyboxPath(std::string path) { skybox_path_ = std::move(path); }

  // The game's UI Toolkit triangles for this frame (drawn over the scene,
  // under ImGui), or null when there is none.
  virtual const UI::UIDrawData* GetUIDrawData() const { return nullptr; }

  // Post-processing for the frame.
  virtual RenderSettings GetRenderSettings() const { return RenderSettings{}; }
  // Every camera to draw this frame at the given output size, in order:
  // RenderTexture cameras, then the main camera, then overlays. Empty means
  // only the current camera (GetCameraProj).
  virtual std::vector<RenderCamera> GetRenderCameras(float width, float height) {
    return {};
  }

  std::vector<StaticVertex> GetStaticVertices();
  std::vector<UINT> GetStaticIndices();

  TextureAtlas& GetAtlas();

  float GetWidth() const;
  float GetHeight() const;
  void SetWidth(float);
  void SetHeight(float);

  entt::registry& GetRegistry() { return object_manager_->GetRegistry(); }
  const entt::registry& GetRegistry() const { return object_manager_->GetRegistry(); }

  void SetInputManager(InputManager*);
  void SetRenderHost(RenderHost* host) { render_host_ = host; }

  void QuitScene();
  bool ShouldQuit() const;

  void SimulatePhysics(int steps);

  virtual void ProcessOnFrame(float alpha);
  void OnTickBegin();

 protected:
  std::shared_ptr<PObjectManager> object_manager_ = nullptr;
  std::shared_ptr<PhysicsEngine> physics_engine_ = nullptr;
  kEntityId player_camera_ = entt::null;
  InputManager* input_manager_ = nullptr;
  RenderHost* render_host_ = nullptr;
  SceneLighting lighting_;
  glm::vec4 clear_color_ = glm::vec4(0.1f, 0.1f, 0.1f, 1.0f);
  std::string skybox_path_;

 private:
  float width_ = 0.0;
  float height_ = 0.0;
  bool should_close = false;
};

